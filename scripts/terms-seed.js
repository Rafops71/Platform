#!/usr/bin/env node
'use strict';
// The published Terms text, as the database holds it.
//
//   npm run terms:seed     write sql/<NNN>_terms_<version>.sql from js/i18n.js
//   npm run check:terms    fail if that file and js/i18n.js disagree
//
// WHY. An acceptance (sql/031) records the SHA-256 of the exact text accepted,
// read from public.terms_versions - not whatever a browser said it showed.
// That only means something if the database's copy IS the page's text. Both
// come from the same terms.* keys here, so a wording change that is not
// re-seeded fails the build instead of leaving members signing one text while
// the record holds another.
//
// The text is assembled in the order terms.js renders it: heading, version,
// intro, placeholder notice, then each section's title and paragraphs.

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');

const SEED_FILE_NUMBERS = { '3.0': '032', '3.1': '036', '3.2': '039', '3.3': '040' };

function load() {
  const stub = { classList: { add() {}, remove() {}, toggle() {} } };
  const ctx = {
    console,
    window: {},
    localStorage: { getItem: () => null, setItem() {} },
    navigator: { language: 'en' },
    document: { documentElement: {}, querySelectorAll: () => [], getElementById: () => stub, addEventListener() {} },
  };
  vm.createContext(ctx);
  for (const f of ['js/i18n.js', 'js/utils.js']) {
    // `const` at the top of a script does not land on the context object, so
    // the names this needs are exported explicitly.
    vm.runInContext(fs.readFileSync(path.join(ROOT, f), 'utf8'), ctx, { filename: f });
  }
  return vm.runInContext('({ STRINGS, TERMS_VERSION, TERMS_SECTIONS, TERMS_SECTION_PARAGRAPHS })', ctx);
}

function canonicalText(S, lang, version, sections, paragraphs) {
  const d = S[lang];
  const get = (k) => {
    if (typeof d[k] !== 'string') throw new Error(`${lang}: missing ${k}`);
    return d[k];
  };
  const out = [get('terms.heading'), get('terms.version').replace('{version}', version),
               get('terms.intro'), get('terms.placeholderNotice')];
  for (const n of sections) {
    out.push(get(`terms.s${n}.title`));
    const count = paragraphs[n];
    if (count) for (let i = 1; i <= count; i++) out.push(get(`terms.s${n}.p${i}`));
    else out.push(get(`terms.s${n}.body`));
  }
  return out.join('\n\n') + '\n';
}

function build() {
  const { STRINGS, TERMS_VERSION, TERMS_SECTIONS, TERMS_SECTION_PARAGRAPHS } = load();
  // Each published version keeps its own migration, written once and never
  // regenerated after it is live. Raising TERMS_VERSION means adding its
  // migration number here.
  const number = SEED_FILE_NUMBERS[TERMS_VERSION];
  if (!number) throw new Error(`no migration number assigned to Terms ${TERMS_VERSION} in SEED_FILE_NUMBERS`);
  const file = `sql/${number}_terms_${TERMS_VERSION.replace(/\./g, '_')}.sql`;
  const rows = ['en', 'es'].map((lang) => {
    const text = canonicalText(STRINGS, lang, TERMS_VERSION, TERMS_SECTIONS, TERMS_SECTION_PARAGRAPHS);
    if (text.includes('$terms$')) throw new Error('the text contains the SQL quote tag $terms$');
    return { lang, text, sha: crypto.createHash('sha256').update(text, 'utf8').digest('hex') };
  });
  const sql = [
    `-- ${number}: publish Terms version ${TERMS_VERSION} into terms_versions (sql/031).`,
    '--',
    '-- GENERATED by scripts/terms-seed.js from js/i18n.js. Do not edit by hand:',
    '-- change the terms.* keys and run `npm run terms:seed`. `npm run check:terms`',
    '-- fails the build when this file and the page disagree.',
    '--',
    '-- Publishing a version is what turns on the sign-in gate: from this row on,',
    '-- has_accepted_current_terms() is false for anyone who has not signed it.',
    '-- Rows are never updated. A changed text is a new version.',
    '',
    'begin;',
    ...rows.map((r) => [
      '',
      `insert into public.terms_versions (version, language, text, sha256) values (`,
      `  '${TERMS_VERSION}', '${r.lang}',`,
      `  $terms$${r.text}$terms$,`,
      `  '${r.sha}'`,
      `) on conflict (version, language) do nothing;`,
      '',
      `do $$ begin`,
      `  if (select sha256 from public.terms_versions where version = '${TERMS_VERSION}' and language = '${r.lang}')`,
      `     is distinct from '${r.sha}' then`,
      `    raise exception 'terms_versions ${TERMS_VERSION}/${r.lang} already holds a different text';`,
      `  end if;`,
      `end $$;`,
    ].join('\n')),
    '',
    'commit;',
    '',
  ].join('\n');
  return { file, sql, rows, number };
}

if (require.main === module) {
  const { file, sql, rows } = build();
  const target = path.join(ROOT, file);
  if (process.argv.includes('--write')) {
    fs.writeFileSync(target, sql);
    console.log(`Wrote ${file}`);
    for (const r of rows) console.log(`  ${r.lang}  ${r.sha}  ${r.text.length} chars`);
  } else {
    const have = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (have !== sql) {
      console.error(`FAIL - ${file} does not match the Terms text in js/i18n.js.`);
      console.error(have === null ? '  The file does not exist.' : '  The wording changed without re-seeding.');
      console.error('  Run `npm run terms:seed`. If this version is already live, raise TERMS_VERSION first.');
      process.exit(1);
    }
    console.log(`OK - ${file} matches the Terms text (${rows.map(r => r.lang + ' ' + r.sha.slice(0, 12)).join(', ')}).`);
  }
}

module.exports = { build };
